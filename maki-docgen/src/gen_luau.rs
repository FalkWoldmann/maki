//! Renders `api_docs()` as a Luau definition file (`maki.d.luau`) for
//! `lute check`. Every function and method is `@checked`, so nonstrict mode
//! reports calls with arguments of the wrong type. Userdata classes become
//! extern types. Nonstrict can't negate table or function types, so those and
//! arrays are `any`.

use std::collections::BTreeSet;
use std::iter;

use maki_lua::docs::{DocKind, FnDoc, ModuleDoc, api_docs};
use maki_lua::docs_render::instance_name;

const HEADER: &str = "-- Generated by maki-docgen from the `maki` API docs. Do not edit.\n";
const ROOT: &str = "maki";
const INDENT: &str = "  ";
const ANY: &str = "any";
const SELF: &str = "self";
const REST: &str = "...";
const ANY_REST: &str = "...any";
const NIL: &str = "nil";
const INTEGER: &str = "integer";
const NUMBER: &str = "number";
const PRIMITIVES: [&str; 4] = ["string", "boolean", "buffer", "true"];
const OPAQUE: [&str; 5] = [ANY, "table", "function", "userdata", "LuaCtx"];
const DUPLICATE_CLASS: &str = "two userdata classes would share the extern type";

pub fn generate() -> String {
    let docs = api_docs();
    let mut out = HEADER.to_owned();
    push_classes(&mut out, &docs);
    out.push_str(&format!("\ndeclare {ROOT}: "));
    push_table(&mut out, ROOT, &docs);
    out.push('\n');
    out
}

/// Luau refuses a definition file that declares one extern type twice.
fn push_classes(out: &mut String, docs: &[&ModuleDoc]) {
    let mut names = BTreeSet::new();
    for class in docs.iter().filter(|m| m.kind == DocKind::Class) {
        let name = instance_name(class);
        assert!(
            names.insert(name),
            "{DUPLICATE_CLASS} `{name}`, rename `{}`",
            class.name
        );
        push_class(out, class, docs);
    }
}

fn push_class(out: &mut String, class: &ModuleDoc, docs: &[&ModuleDoc]) {
    out.push_str(&format!(
        "\ndeclare extern type {} with\n",
        instance_name(class)
    ));
    for f in class.fns {
        if f.value {
            out.push_str(&format!("{INDENT}{}: {ANY}\n", f.name));
            continue;
        }
        let (params, returns) = signature(class.name, f, docs);
        let params: Vec<String> = iter::once(SELF.to_owned()).chain(params).collect();
        out.push_str(&format!(
            "{INDENT}@checked function {}({}): {returns}\n",
            f.name,
            params.join(", ")
        ));
    }
    out.push_str("end\n");
}

fn push_table(out: &mut String, path: &str, docs: &[&ModuleDoc]) {
    let depth = path.matches('.').count();
    let indent = INDENT.repeat(depth + 1);
    out.push_str("{\n");
    for f in docs.iter().filter(|m| m.name == path).flat_map(|m| m.fns) {
        let ty = if f.value {
            ANY.to_owned()
        } else {
            let (params, returns) = signature(path, f, docs);
            format!("@checked ({}) -> {returns}", params.join(", "))
        };
        out.push_str(&format!("{indent}{}: {ty},\n", f.name));
    }
    let children: BTreeSet<&str> = docs
        .iter()
        .filter(|m| m.kind == DocKind::Table)
        .filter_map(|m| m.name.rsplit_once('.'))
        .filter(|(parent, _)| *parent == path)
        .map(|(_, key)| key)
        .collect();
    for key in children {
        out.push_str(&format!("{indent}{key}: "));
        push_table(out, &format!("{path}.{key}"), docs);
        out.push_str(",\n");
    }
    out.push_str(&format!("{}}}", INDENT.repeat(depth)));
}

/// The Luau parameters and return pack of `path.f`.
fn signature(path: &str, f: &FnDoc, docs: &[&ModuleDoc]) -> (Vec<String>, String) {
    let resolve = |ty: &str| match ty {
        REST => ANY_REST.to_owned(),
        _ => luau_type(ty, docs)
            .unwrap_or_else(|| panic!("`{path}.{}`: no Luau type for `{ty}`", f.name)),
    };
    let params: Vec<String> = f
        .params
        .iter()
        .map(|p| parameter(p.name, &resolve(p.ty)))
        .collect();
    let returns: Vec<String> = f
        .returns
        .strip_prefix('(')
        .and_then(|r| r.split_once(')'))
        .map_or(f.returns, |(types, _)| types)
        .split_terminator(", ")
        .map(resolve)
        .collect();
    (params, format!("({})", returns.join(", ")))
}

/// Renders a doc parameter such as `{path}`, `{opts?}` or `{...}`. A name
/// ending in `?` may be left out of the call, so its type also takes `nil`.
fn parameter(name: &str, ty: &str) -> String {
    let name = name.trim_matches(['{', '}']);
    if name == REST {
        return format!("{REST}{ty}");
    }
    match name.strip_suffix('?') {
        Some(name) if ty != ANY && !ty.ends_with('?') => format!("{name}: {ty}?"),
        optional => format!("{}: {ty}", optional.unwrap_or(name)),
    }
}

/// Maps a doc type such as `string|nil`, `table?` or `Node?` to Luau, `None`
/// if unknown.
fn luau_type(ty: &str, docs: &[&ModuleDoc]) -> Option<String> {
    let (ty, mut nullable) = ty
        .strip_suffix('?')
        .map_or((ty, false), |base| (base, true));
    let mut members = Vec::new();
    let mut opaque = false;
    for atom in ty.split('|') {
        match atom {
            NIL => nullable = true,
            INTEGER => members.push(NUMBER),
            _ if PRIMITIVES.contains(&atom) => members.push(atom),
            _ if is_opaque(atom, docs) => opaque = true,
            _ => members.push(class(atom, docs)?),
        }
    }
    if opaque {
        return Some(ANY.to_owned());
    }
    let union = members.join(" | ");
    Some(if nullable { format!("{union}?") } else { union })
}

/// Tables, functions and arrays.
fn is_opaque(atom: &str, docs: &[&ModuleDoc]) -> bool {
    OPAQUE.contains(&atom)
        || atom
            .strip_suffix("[]")
            .is_some_and(|element| luau_type(element, docs).is_some())
}

/// The extern type of a userdata class named in full (`maki.net.Conn`) or short (`Conn`).
fn class(atom: &str, docs: &[&ModuleDoc]) -> Option<&'static str> {
    docs.iter()
        .find(|m| m.kind == DocKind::Class && (m.name == atom || instance_name(m) == atom))
        .map(|m| instance_name(m))
}

#[cfg(test)]
mod tests {
    use std::panic;

    use maki_lua::docs::{DocKind, FnDoc, ModuleDoc, ParamDoc, api_docs};
    use test_case::test_case;

    use super::{DUPLICATE_CLASS, luau_type, parameter, push_class, push_classes};

    const CURSOR: ModuleDoc = ModuleDoc {
        name: "maki.test.Cursor",
        kind: DocKind::Class,
        desc: "",
        fns: &[
            FnDoc {
                name: "next",
                args: "{node}, {limit?}",
                desc: "",
                params: &[
                    ParamDoc {
                        name: "{node}",
                        ty: "Node",
                        desc: "",
                    },
                    ParamDoc {
                        name: "{limit?}",
                        ty: "integer",
                        desc: "",
                    },
                ],
                returns: "(Cursor?) The next cursor.",
                example: "",
                guard: None,
                value: false,
            },
            FnDoc {
                name: "kind",
                args: "",
                desc: "",
                params: &[],
                returns: "",
                example: "",
                guard: None,
                value: true,
            },
        ],
    };

    const CONN_TWIN: ModuleDoc = ModuleDoc {
        name: "maki.ipc.Conn",
        kind: DocKind::Class,
        desc: "",
        fns: &[],
    };

    #[test]
    fn rejects_classes_sharing_a_short_name() {
        let docs: Vec<&ModuleDoc> = api_docs().into_iter().chain([&CONN_TWIN]).collect();
        let payload = panic::catch_unwind(|| push_classes(&mut String::new(), &docs))
            .expect_err("duplicate extern type accepted");
        let message = payload
            .downcast_ref::<String>()
            .expect("formatted panic message");
        assert!(message.starts_with(DUPLICATE_CLASS), "{message}");
    }

    #[test]
    fn renders_class_as_extern_type() {
        let docs: Vec<&ModuleDoc> = api_docs().into_iter().chain([&CURSOR]).collect();
        let mut out = String::new();
        push_class(&mut out, &CURSOR, &docs);
        assert_eq!(
            out,
            "\ndeclare extern type Cursor with\n  \
             @checked function next(self, node: Node, limit: number?): (Cursor?)\n  \
             kind: any\nend\n"
        );
    }

    #[test_case("{path}", "string", "path: string" ; "required")]
    #[test_case("{timeout_ms?}", "number", "timeout_ms: number?" ; "optional_name_takes_nil")]
    #[test_case("{limit?}", "number?", "limit: number?" ; "optional_name_with_optional_type")]
    #[test_case("{opts?}", "any", "opts: any" ; "optional_any_stays_any")]
    #[test_case("{...}", "string", "...string" ; "rest")]
    fn renders_parameters(name: &str, ty: &str, expected: &str) {
        assert_eq!(parameter(name, ty), expected);
    }

    #[test_case("integer?", Some("number?") ; "optional")]
    #[test_case("string|nil", Some("string?") ; "nil_union_is_optional")]
    #[test_case("table?", Some("any") ; "table_is_any")]
    #[test_case("string|string[]", Some("any") ; "array_is_any")]
    #[test_case("Node|nil", Some("Node?") ; "class")]
    #[test_case("maki.net.Conn?", Some("Conn?") ; "class_by_full_name")]
    #[test_case("string|Node", Some("string | Node") ; "class_in_union")]
    #[test_case("Node|table", Some("any") ; "class_with_table_is_any")]
    #[test_case("Node[]", Some("any") ; "class_array_is_any")]
    #[test_case("strng", None ; "unknown_type")]
    #[test_case("Nod", None ; "unknown_class")]
    #[test_case("Nod[]", None ; "unknown_array_element")]
    fn maps_doc_types(ty: &str, expected: Option<&str>) {
        assert_eq!(luau_type(ty, &api_docs()).as_deref(), expected);
    }
}
